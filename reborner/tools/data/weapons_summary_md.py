def revised():
	out = {}
	cur = None
	fam = {'คม': 'SL', 'ทุบ': 'CR', 'แทง': 'PC', 'ยิง': 'ST', 'กล': 'DV', 'มือเปล่า': 'BD'}
	for ln in open(os.path.join(D60, 'WEAPON_DESCRIPTIONS_60.md'), encoding='utf-8'):
		m = re.match(r'## สาย(\S+)', ln)
		if m:
			cur = fam[m.group(1)]
		m = re.match(r'(\d+)\. \*\*(.+?) \(.*?\(ฉบับแก้([^)]*)\)', ln)
		if m and cur:
			out['%s-%s' % (cur, m.group(1))] = m.group(2)
	return out


